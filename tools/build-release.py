#!/usr/bin/env python3
"""Regenerate the immutable PWA release after editing any frontend file."""
import hashlib,json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
files=['index.html','session-schema.js','storage.js','styles.css','exercise-library.js','exercise-coaching.js','gym-equipment-data.js','gym-inventory.js','training-plan.js','app.js','app-core.js','workout-log.js','analytics.js','exercise-ui.js','record-model.js','interface-tools.js','app-enhancements.js','app-enhancements.css','sync-engine.js','backup.js','workout-tools.js','pwa.js','manifest.json','icon192.png','icon512.png']
manifest={name:hashlib.sha256((root/name).read_bytes()).hexdigest() for name in files}
build=hashlib.sha256(json.dumps(manifest,sort_keys=True).encode()).hexdigest()[:16]
sw='''// Generated by tools/build-release.py. Core bytes are immutable within a release.
const CACHE='fit-tracker-v10-BUILD';
const FILES=MANIFEST;
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const entries=await Promise.all(Object.entries(FILES).map(async([name,hash])=>{
  const response=await fetch(new URL(name,self.registration.scope),{cache:'no-store'});
  if(!response.ok)throw new Error('Incomplete release: '+name);
  const bytes=await response.clone().arrayBuffer();
  const actual=[...new Uint8Array(await crypto.subtle.digest('SHA-256',bytes))].map(x=>x.toString(16).padStart(2,'0')).join('');
  if(actual!==hash)throw new Error('Mixed release: '+name);
  return [new URL(name,self.registration.scope).href,response];
 }));
 const cache=await caches.open(CACHE);await Promise.all(entries.map(([url,response])=>cache.put(url,response)));
 // No skipWaiting: the old app continues with its complete old release.
})()));
self.addEventListener('message',event=>{if(event.data?.type==='ACTIVATE')self.skipWaiting();});
self.addEventListener('activate',event=>event.waitUntil((async()=>{
 for(const key of await caches.keys())if(key.startsWith('fit-tracker-')&&key!==CACHE)await caches.delete(key);
 await self.clients.claim();
})()));
self.addEventListener('fetch',event=>{
 const request=event.request,url=new URL(request.url);if(request.method!=='GET'||url.origin!==self.location.origin)return;
 const scope=new URL(self.registration.scope),relative=url.pathname.startsWith(scope.pathname)?url.pathname.slice(scope.pathname.length):null;
 if(relative===null)return;
 const name=request.mode==='navigate'?'index.html':relative;
 if(!Object.hasOwn(FILES,name))return;
 event.respondWith((async()=>{const cached=await(await caches.open(CACHE)).match(new URL(name,scope).href);return cached||Response.error();})());
});
'''.replace('BUILD',build).replace('MANIFEST',json.dumps(manifest,separators=(',',':')))
(root/'sw.js').write_text(sw)
print('Release',build,len(files),'verified files')
